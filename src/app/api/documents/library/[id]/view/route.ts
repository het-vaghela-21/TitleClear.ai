import { NextRequest, NextResponse } from "next/server";
import { currentUser, unauthorized } from "@/lib/auth/session";
import { getDoc, readDocBytes } from "@/lib/doc-library/store";
import { viewMode } from "@/lib/doc-library/types";

/**
 * GET /api/documents/library/[id]/view
 *
 * Everything the viewer needs for one document, in one request:
 *
 *   { doc, mode: "pdf" | "image" }   → render the raw route in an iframe/img
 *   { doc, mode: "html", html }      → a .docx converted to HTML
 *   { doc, mode: "text", text }      → a text file, decoded as UTF-8
 *   { doc, mode: "none" }            → no preview; download it instead
 *
 * The converted HTML is generated by mammoth from the document's own
 * structure — it is never passed through from the file — and the client
 * still renders it inside a `sandbox=""` iframe, so a hostile .docx has no
 * way to run script on this origin.
 */

/** Beyond this a "preview" stops being useful and just floods the client. */
const MAX_TEXT_CHARS = 400_000;

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ id: string }> },
) {
  const user = await currentUser();
  if (!user) return unauthorized();

  const { id } = await params;
  const doc = await getDoc(user.id, id);
  if (!doc) {
    return NextResponse.json({ error: "Document not found" }, { status: 404 });
  }

  const mode = viewMode(doc);
  if (mode === "pdf" || mode === "image" || mode === "none") {
    return NextResponse.json({ doc, mode });
  }

  const bytes = await readDocBytes(doc);
  if (!bytes) {
    return NextResponse.json({ error: "File is missing from the store" }, { status: 404 });
  }

  if (mode === "text") {
    const full = new TextDecoder("utf-8").decode(bytes);
    return NextResponse.json({
      doc,
      mode,
      text: full.slice(0, MAX_TEXT_CHARS),
      truncated: full.length > MAX_TEXT_CHARS,
    });
  }

  // mode === "html" — a .docx.
  try {
    const mammoth = (await import("mammoth")).default;
    const { value, messages } = await mammoth.convertToHtml({ buffer: bytes });
    return NextResponse.json({
      doc,
      mode,
      html: value,
      // Things mammoth couldn't map (unusual styles, embedded objects) —
      // shown as a note so a thin-looking preview is explainable.
      warnings: messages.filter((m) => m.type === "warning").map((m) => m.message),
    });
  } catch {
    return NextResponse.json({
      doc,
      mode: "none",
      error: "This Word file could not be converted for preview.",
    });
  }
}
